"""
Synthesis Agent and Escalation Gate nodes.

- Escalation Gate: Terminates cases requiring human review directly with zero LLM calls.
- Synthesis Agent: Formats customer-facing explanation for approved/denied/provisional cases
  using exactly ONE Gemini call with strict GeminiSynthesisOutput schema.
- Instruments both nodes with OpenTelemetry spans and token telemetry.
"""

import json
from typing import Any, Dict, Optional
from google import genai
from google.genai import errors as genai_errors
from opentelemetry.trace import Status, StatusCode
from openinference.semconv.trace import SpanAttributes

from src.config.settings import get_settings
from src.schemas.gemini_schemas import GeminiSynthesisOutput
from src.utils.gemini_config import build_generate_content_config
from src.observability.tracing import trace_span


SYNTHESIS_PROMPT = """You are a polite, professional banking customer dispute resolution specialist.
Write a clear, direct resolution letter for the cardholder addressing their specific dispute claim and refund request.
Use ONLY the facts and decision provided below. DO NOT invent or alter the decision, amounts, or policy rules.

Dispute Category: {category}
Customer Claim: {claim_summary}
Action Taken / Decision: {action}
Dispute Amount: ${amount:.2f}
Applicable Policy Rule: {rule_id} ({rule_title})
Filing Limit: {max_days} days
Required Evidence: {evidence}
Synthetic Regulation Reference: {citation}

Instructions:
- Directly address the customer's specific claim and refund request. Clearly inform them of the outcome regarding their dispute.
- Provide practical, concise next steps for the customer.
- Cite the applicable benchmark policy rule and filing window factually.
- Include a brief regulatory disclaimer stating that this resolution was generated by an automated triage copilot.

Format strictly adhering to the schema:
- customer_explanation: Direct, courteous resolution directly addressing the customer's claim and refund decision
- next_steps: Practical next steps for the customer
- policy_reference_summary: Concise citation of the governing rule ({rule_id}) and timeline
- disclaimer: Brief standard bank notice regarding automated dispute processing"""


def escalation_gate_node(state: Dict[str, Any]) -> Dict[str, Any]:
    """
    Structured escalation gate.
    If escalation is required, generates structured handoff packet with ZERO LLM calls.
    Avoids fabricating default numbers, scores, or policies when MCP data is unavailable.
    """
    if not state.get("escalation_required"):
        return {}

    with trace_span(
        name="escalation_gate",
        span_kind="AGENT",
        agent="escalation_gate",
        attributes={
            "agent.role": "escalation_gate",
            "escalation.reason": state.get("escalation_reason", "Mandatory compliance review"),
            "escalation.tier": state.get("precedence_level", 1),
        },
    ):
        tx = state.get("transaction") or {}
        tx_id = tx.get("transaction_id", state.get("transaction_id", "N/A"))

        # Amount representation: only numeric if extracted or from transaction
        raw_amount = state.get("extracted_amount") if state.get("extracted_amount") is not None else tx.get("amount")
        amount_str = f"${float(raw_amount):.2f}" if raw_amount is not None else "UNAVAILABLE"

        reason = state.get("escalation_reason") or "Mandatory compliance review"

        # Fraud representation: must NEVER substitute 0.0 or sentinels if unavailable
        raw_fraud = state.get("fraud_score")
        if raw_fraud is not None:
            risk_level = state.get("risk_level") or "ASSESSED"
            fraud_str = f"{float(raw_fraud):.1f}/100 ({risk_level})"
        else:
            fraud_str = "UNAVAILABLE"

        category = state.get("dispute_category") or "UNAVAILABLE"
        rule_id = state.get("selected_rule_id") or "UNAVAILABLE"

        factors = state.get("top_risk_factors") or []
        factors_str = ", ".join(factors) if factors else "None"

        evidence = state.get("evidence_required") or []
        evidence_str = ", ".join(evidence) if evidence else "UNAVAILABLE"

        # If data is unavailable or transaction lookup failed, emit strict missing-data notice
        if state.get("data_unavailable") or not state.get("transaction"):
            escalation_packet = (
                f"=== AUTOMATED TRIAGE ESCALATION NOTICE ===\n"
                f"STATUS: ROUTED TO HUMAN FRAUD / DISPUTE SPECIALIST\n"
                f"Recommended Action : INVESTIGATE\n"
                f"Precedence Level   : Tier {state.get('precedence_level', 1)}\n"
                f"Escalation Reason  : {reason}\n"
                f"Transaction Record : {tx_id} (Amount: {amount_str})\n"
                f"Fraud Risk Metric  : {fraud_str}\n"
                f"Dispute Category   : {category}\n"
                f"Applied Policy Rule: {rule_id}\n"
                f"Identified Factors : {factors_str}\n"
                f"Evidence Required  : {evidence_str}\n"
                f"Data Availability  : Core banking transaction record is unavailable. No automated decision or score fabricated.\n"
                f"=========================================="
            )
        else:
            escalation_packet = (
                f"=== AUTOMATED TRIAGE ESCALATION NOTICE ===\n"
                f"STATUS: ROUTED TO HUMAN FRAUD / DISPUTE SPECIALIST\n"
                f"Recommended Action : INVESTIGATE\n"
                f"Precedence Level   : Tier {state.get('precedence_level', 1)}\n"
                f"Escalation Reason  : {reason}\n"
                f"Transaction Record : {tx_id} ({amount_str})\n"
                f"Fraud Risk Metric  : {fraud_str}\n"
                f"Identified Factors : {factors_str}\n"
                f"Evidence Required  : {evidence_str}\n"
                f"=========================================="
            )

        return {
            "final_response": escalation_packet,
            "synthesis_result": escalation_packet,
        }


async def synthesis_agent_node(state: Dict[str, Any]) -> Dict[str, Any]:
    """LangGraph node for Gemini customer communication synthesis."""
    if state.get("escalation_required"):
        return {}

    with trace_span(
        name="synthesis",
        span_kind="AGENT",
        agent="synthesis",
        attributes={"agent.role": "communication_synthesis"},
    ) as agent_span:
        settings = get_settings()
        current_tokens = state.get("cumulative_tokens", 0)

        # Budget ceiling check
        if current_tokens >= settings.max_cumulative_tokens:
            fallback_msg = (
                f"Your dispute regarding transaction {state.get('transaction_id')} has been processed with outcome: "
                f"{state.get('recommended_action')}. Contact support for complete documentation."
            )
            return {
                "synthesis_result": fallback_msg,
                "final_response": fallback_msg,
                "execution_errors": state.get("execution_errors", []) + ["Synthesis skipped: token ceiling reached"],
            }

        if not settings.gemini_api_key:
            fallback_msg = (
                f"Outcome: {state.get('recommended_action')}. Policy rule: {state.get('selected_rule_id')}. "
                f"Contact customer service for assistance."
            )
            return {
                "synthesis_result": fallback_msg,
                "final_response": fallback_msg,
            }

        tx = state.get("transaction") or {}
        amount = float(state.get("extracted_amount") or tx.get("amount") or 0.0)

        prompt = SYNTHESIS_PROMPT.format(
            category=state.get("dispute_category", "general_dispute"),
            claim_summary=state.get("claim_summary", "N/A"),
            action=state.get("recommended_action", "investigate"),
            rule_id=state.get("selected_rule_id", "SYNTH-RULE-BENCHMARK"),
            rule_title=state.get("rule_title", "Synthetic Network Rule"),
            max_days=state.get("max_filing_days", 120),
            evidence=", ".join(state.get("evidence_required", ["Written statement"])),
            citation=state.get("synthetic_citation", "Synthetic Operating Regulations"),
            amount=amount,
        )

        client = genai.Client(api_key=settings.gemini_api_key)
        config = build_generate_content_config(
            model_name=settings.gemini_model,
            temperature=0.0,
            max_output_tokens=settings.synthesis_max_output_tokens,
            response_mime_type="application/json",
            response_schema=GeminiSynthesisOutput,
            thinking_level=settings.gemini_thinking_level,
            thinking_budget=settings.gemini_thinking_budget,
        )

        response = None
        last_error: Optional[str] = None

        with trace_span(
            name="gemini.generate_content",
            span_kind="LLM",
            agent="synthesis",
            attributes={
                "llm.model_name": settings.gemini_model,
                SpanAttributes.INPUT_VALUE: prompt[:500],
            },
        ) as llm_span:
            import asyncio
            for attempt in range(2):
                try:
                    response = await asyncio.wait_for(
                        client.aio.models.generate_content(
                            model=settings.gemini_model,
                            contents=prompt,
                            config=config,
                        ),
                        timeout=25.0,
                    )
                    break
                except asyncio.TimeoutError:
                    last_error = "Gemini API request timed out after 25s"
                    if attempt == 0:
                        await asyncio.sleep(2.0)
                        continue
                except genai_errors.APIError as e:
                    if getattr(e, "code", 0) == 429:
                        llm_span.set_status(Status(StatusCode.ERROR, f"Gemini 429 Rate Limit: {str(e)}"))
                        fallback_msg = f"Dispute Outcome: {state.get('recommended_action')}. (Notice: Generated in quota fallback mode)."
                        return {
                            "synthesis_result": fallback_msg,
                            "final_response": fallback_msg,
                            "execution_errors": state.get("execution_errors", []) + ["Synthesis 429 Rate Limit"],
                        }
                    last_error = str(e)
                    if attempt == 0:
                        await asyncio.sleep(2.0)
                        continue
                except Exception as e:
                    last_error = str(e)
                    if attempt == 0:
                        await asyncio.sleep(2.0)
                        continue

            if response and response.usage_metadata:
                usage = response.usage_metadata
                p_tokens = getattr(usage, "prompt_token_count", None)
                o_tokens = getattr(usage, "candidates_token_count", None)
                th_tokens = getattr(usage, "thoughts_token_count", None)
                tot_tokens = getattr(usage, "total_token_count", None)

                llm_span.set_attribute("gen_ai.system", "Google Gemini")
                llm_span.set_attribute("gen_ai.request.model", settings.gemini_model)
                if p_tokens is not None:
                    llm_span.set_attribute("gen_ai.usage.input_tokens", p_tokens)
                    llm_span.set_attribute(SpanAttributes.LLM_TOKEN_COUNT_PROMPT, p_tokens)
                    llm_span.set_attribute("llm.token_count.prompt", p_tokens)
                if o_tokens is not None:
                    llm_span.set_attribute("gen_ai.usage.output_tokens", o_tokens)
                    llm_span.set_attribute(SpanAttributes.LLM_TOKEN_COUNT_COMPLETION, o_tokens)
                    llm_span.set_attribute("llm.token_count.completion", o_tokens)
                if tot_tokens is not None:
                    llm_span.set_attribute("gen_ai.usage.total_tokens", tot_tokens)
                    llm_span.set_attribute(SpanAttributes.LLM_TOKEN_COUNT_TOTAL, tot_tokens)
                    llm_span.set_attribute("llm.token_count.total", tot_tokens)
                if th_tokens is not None:
                    llm_span.set_attribute("gen_ai.usage.thinking_tokens", th_tokens)
                    llm_span.set_attribute("llm.token_count.thinking", th_tokens)

        if not response or not response.parsed:
            fallback_msg = (
                f"Dispute Status: {state.get('recommended_action')}. Policy rule applied: {state.get('selected_rule_id')}."
            )
            return {
                "synthesis_result": fallback_msg,
                "final_response": fallback_msg,
                "execution_errors": state.get("execution_errors", []) + [f"Synthesis parse error: {last_error}"],
            }

        parsed: GeminiSynthesisOutput = response.parsed

        # Telemetry
        usage = response.usage_metadata
        total_tokens = getattr(usage, "total_token_count", 0)
        call_count = state.get("gemini_call_count", 0) + 1
        new_cumulative = current_tokens + total_tokens

        formatted_output = (
            f"Dear Customer,\n\n"
            f"{parsed.customer_explanation}\n\n"
            f"Next Steps:\n{parsed.next_steps}\n\n"
            f"Policy Reference:\n{parsed.policy_reference_summary}\n\n"
            f"Notice: {parsed.disclaimer}"
        )

        return {
            "synthesis_result": formatted_output,
            "final_response": formatted_output,
            "gemini_call_count": call_count,
            "cumulative_tokens": new_cumulative,
        }
