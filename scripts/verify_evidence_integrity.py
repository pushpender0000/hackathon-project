"""
Verification script for Evidence Integrity, Failure Analysis Resolvability,
Pricing Architecture, and Governance Hygiene.

Audits:
A. Every failure-analysis citation resolves against traces/phoenix_spans.jsonl,
   logs/tool_calls.jsonl, and logs/agent_actions.jsonl.
B. All pricing values are generated from the centralized pricing configuration.
C. Golden signals contain all required acting/tool/model latency fields.
D. No unauthorized Visa/Mastercard policy claims exist for synthetic policy data.
E. golden_signals.json uses ONLY the intended final 5-case clean run (no historical contamination).
F. Golden signal token totals match the sum of actual LLM spans in the trace file.
G. Notional cost matches centralized pricing calculation using reported tokens.
H. evaluation_report.json was generated by the evaluation pipeline (not manually edited).
I. No secrets or unmasked PANs exist in logs, traces, or evaluation outputs.
"""

import sys
import re
import json
from pathlib import Path

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config.settings import get_settings
from src.observability.pricing import PRICING_CONFIG, calculate_cost, get_model_pricing


def verify_all():
    settings = get_settings()
    root = settings.workspace_root
    traces_file = root / "traces" / "phoenix_spans.jsonl"
    tool_file = root / "logs" / "tool_calls.jsonl"
    action_file = root / "logs" / "agent_actions.jsonl"
    golden_file = root / "reports" / "golden_signals.json"
    dashboard_csv = root / "reports" / "dashboard_data.csv"
    failure_doc = root / "docs" / "failure-analysis.md"

    print("=" * 70)
    print("PHASE 3 FINAL EVIDENCE INTEGRITY VERIFICATION SUITE")
    print("=" * 70)

    # ----------------------------------------------------
    # CHECK A: Every failure-analysis citation resolves
    # ----------------------------------------------------
    print("\n[CHECK A] Resolving Failure Analysis Citations...")
    assert traces_file.exists(), f"Missing {traces_file}"
    assert tool_file.exists(), f"Missing {tool_file}"
    assert action_file.exists(), f"Missing {action_file}"
    assert failure_doc.exists(), f"Missing {failure_doc}"

    with open(traces_file, "r", encoding="utf-8") as f:
        spans = [json.loads(line) for line in f if line.strip()]
    with open(tool_file, "r", encoding="utf-8") as f:
        tools = [json.loads(line) for line in f if line.strip()]
    with open(action_file, "r", encoding="utf-8") as f:
        actions = [json.loads(line) for line in f if line.strip()]

    span_keys = {(s.get("trace_id"), s.get("span_id")) for s in spans}
    trace_ids = {s.get("trace_id") for s in spans}
    span_ids = {s.get("span_id") for s in spans}

    # Failure 1: MCP Gateway 504 Timeout — DISP-MCP-FAIL
    f1_trace = "f5bc084d9efe740139006cbd7f4aea14"
    f1_root_span = "7a960910e8470bdf"
    assert f1_trace in trace_ids, f"Failure 1 trace {f1_trace} not found in spans!"
    assert (f1_trace, f1_root_span) in span_keys, f"Failure 1 root span {(f1_trace, f1_root_span)} not found!"

    f1_tool_rec = next((t for t in tools if t.get("args", {}).get("transaction_id") == "TX-MCP-FAIL" and t.get("status") == "ERROR"), None)
    assert f1_tool_rec is not None, "Failure 1 tool log record with TX-MCP-FAIL and ERROR status not found!"
    print(f"  [PASS] Failure 1 resolves to trace={f1_trace}, root_span={f1_root_span}, tool_log={f1_tool_rec['timestamp']}")

    # Failure 2: Adversarial Prompt Injection — DISP-013
    f2_trace = "29118f8d85178c4282b3f44633e5ebb2"
    f2_root_span = "14dcb63469ac95b5"
    assert f2_trace in trace_ids, f"Failure 2 trace {f2_trace} not found in spans!"
    assert (f2_trace, f2_root_span) in span_keys, f"Failure 2 root span {(f2_trace, f2_root_span)} not found!"

    f2_action_rec = next((a for a in actions if a.get("action") == "BLOCK_PROMPT_INJECTION" and a.get("decision") == "BLOCKED"), None)
    assert f2_action_rec is not None, "Failure 2 action log with BLOCK_PROMPT_INJECTION not found!"
    print(f"  [PASS] Failure 2 resolves to trace={f2_trace}, root_span={f2_root_span}, action_log={f2_action_rec['timestamp']}")

    # Failure 3: Rate-Limit / Token Telemetry Fix — verified by real tokens in DISP-001 LLM spans
    f3_trace = "d30776c3b3ea9666c3d40fa14dfb81a5"
    f3_classifier_llm_span = "4fde2a4edf6ead40"
    f3_root_span = "b4f943eca835630b"
    assert (f3_trace, f3_classifier_llm_span) in span_keys, f"Failure 3 classifier LLM span {(f3_trace, f3_classifier_llm_span)} not found!"
    assert (f3_trace, f3_root_span) in span_keys, f"Failure 3 root span {(f3_trace, f3_root_span)} not found!"
    f3_span_data = next(s for s in spans if s.get("span_id") == f3_classifier_llm_span)
    input_toks = f3_span_data.get("token_usage", {}).get("prompt_tokens")
    assert input_toks is not None and int(input_toks) > 0, f"Failure 3 span does not contain non-zero input tokens! Got: {input_toks}"
    print(f"  [PASS] Failure 3 resolves to trace={f3_trace}, span={f3_classifier_llm_span}, input_tokens={input_toks} (non-zero token telemetry confirmed).")

    # ----------------------------------------------------
    # CHECK B: Pricing centralized and free-tier distinguished
    # ----------------------------------------------------
    print("\n[CHECK B] Verifying Centralized Pricing Architecture...")
    assert golden_file.exists(), f"Missing {golden_file}"
    with open(golden_file, "r", encoding="utf-8") as f:
        gs_data = json.load(f)
    gs_signals = gs_data.get("signals", {})
    gs_input = gs_signals.get("input_tokens", 0)
    gs_output = gs_signals.get("output_tokens", 0)

    rates = get_model_pricing(settings.gemini_model)
    # Pricing for gemini-3.5-flash-lite Standard: $0.30/1M input, $2.50/1M output (incl. thinking)
    assert rates["input_cost_per_million"] > 0, f"Input rate must be > 0: {rates['input_cost_per_million']}"
    assert rates["output_cost_per_million"] > 0, f"Output rate must be > 0: {rates['output_cost_per_million']}"

    # Authoritative calculation using golden signals tokens and centralized calculate_cost
    golden_cost = calculate_cost(settings.gemini_model, gs_input, gs_output)
    expected_notional = round(
        (gs_input * rates["input_cost_per_million"] / 1e6) + (gs_output * rates["output_cost_per_million"] / 1e6), 8
    )
    assert golden_cost["notional_cost_usd"] == expected_notional, (
        f"Notional cost mismatch: expected {expected_notional}, got {golden_cost['notional_cost_usd']}"
    )
    assert golden_cost["actual_api_charge_usd"] is None, (
        f"actual_api_charge_usd must be None (not available from runtime telemetry), got: {golden_cost['actual_api_charge_usd']}"
    )
    print(f"  [PASS] Centralized pricing config verified: {golden_cost['pricing_assumption']}")
    print(f"  [PASS] Notional cost calculation verified: ${golden_cost['notional_cost_usd']:.8f}")
    print(f"  [PASS] actual_api_charge_usd correctly reported as None (not available from telemetry).")

    # ----------------------------------------------------
    # CHECK C: Golden signals contains acting/tool/model latency fields
    # ----------------------------------------------------
    print("\n[CHECK C] Verifying Golden Signals Output Fields...")
    assert golden_file.exists(), f"Missing {golden_file}"
    with open(golden_file, "r", encoding="utf-8") as f:
        gs = json.load(f)

    signals = gs.get("signals", {})
    required_signal_fields = [
        "end_to_end_latency_ms",
        "agent_acting_latency_ms",
        "tool_latency_ms",
        "llm_model_latency_ms",
        "thinking_latency_ms",
        "input_tokens",
        "output_tokens",
        "thinking_tokens",
        "gemini_call_count",
        "estimated_notional_cost_usd",
        "actual_api_charge_usd",
        "deterministic_accuracy",
        "hallucination",
        "faithfulness",
        "relevance",
    ]
    for field in required_signal_fields:
        assert field in signals, f"Field '{field}' missing from golden_signals.json signals block!"
        val = signals[field]
        if field in ("thinking_latency_ms", "thinking_tokens") and val is None:
            notes_key = "thinking_latency_notes" if field == "thinking_latency_ms" else "thinking_tokens_notes"
            notes_val = signals.get(notes_key)
            assert notes_val is not None, f"Missing notes for {field} (expected notes key: {notes_key})"
            print(f"  [PASS] Field '{field}' correctly represented as null with notes: '{notes_val}'")
        elif field == "actual_api_charge_usd":
            assert val is None, f"actual_api_charge_usd must be null (not available from runtime telemetry), got: {val}"
            note = signals.get("actual_api_charge_note", "")
            assert note, "actual_api_charge_note must be present when actual_api_charge_usd is null"
            print(f"  [PASS] Field '{field}' correctly null; note: '{note}'")
        else:
            print(f"  [PASS] Field '{field}': {val}")

    # ----------------------------------------------------
    # CHECK D: No unauthorized Visa/Mastercard policy claims
    # ----------------------------------------------------
    print("\n[CHECK D] Verifying Synthetic Policy Corpus Terminology...")

    doc_paths = list(root.glob("docs/**/*.md")) + list(root.glob("reports/**/*.md"))
    forbidden_patterns = [
        re.compile(r"\bactual Visa\b", re.IGNORECASE),
        re.compile(r"\bactual Mastercard\b", re.IGNORECASE),
        re.compile(r"\bofficial Visa\b", re.IGNORECASE),
        re.compile(r"\bofficial Mastercard\b", re.IGNORECASE),
        re.compile(r"\bVisa/Mastercard policy\b", re.IGNORECASE),
    ]
    for dp in doc_paths:
        content = dp.read_text(encoding="utf-8")
        for pattern in forbidden_patterns:
            match = pattern.search(content)
            assert match is None, f"Forbidden real network claim '{match.group(0)}' found in {dp}!"
    print("  [PASS] Zero unauthorized Visa/Mastercard policy claims found across documentation and reports.")

    # ----------------------------------------------------
    # CHECK E: golden_signals.json uses only final 5-case clean run
    # ----------------------------------------------------
    print("\n[CHECK E] Verifying golden_signals.json uses ONLY the final 5 clean-run cases...")
    assert golden_file.exists(), f"Missing {golden_file}"
    with open(golden_file, "r", encoding="utf-8") as f:
        gs_data = json.load(f)
    gs_meta = gs_data.get("metadata", {})
    source_run_count = gs_meta.get("source_run_count")
    source_cases = gs_meta.get("source_cases", [])
    expected_cases = sorted(["DISP-001", "DISP-003", "DISP-005", "DISP-013", "DISP-MCP-FAIL"])
    assert source_run_count == 5, (
        f"golden_signals source_run_count must be 5 (the 5 clean-run cases); got {source_run_count}. "
        f"Re-run generate_observability.py --clean --cases DISP-001 ... and then generate_golden_signals.py."
    )
    assert sorted(source_cases) == expected_cases, (
        f"golden_signals source_cases mismatch!\n  Expected: {expected_cases}\n  Got: {sorted(source_cases)}"
    )
    print(f"  [PASS] source_run_count = {source_run_count} — only the 5 final cases.")
    print(f"  [PASS] source_cases = {source_cases}")

    # ----------------------------------------------------
    # CHECK F: Token cross-check — golden totals == sum of LLM spans
    # ----------------------------------------------------
    print("\n[CHECK F] Token Cross-Check: golden totals vs. sum of LLM spans...")
    llm_spans = [s for s in spans if s.get("span_kind") == "LLM" and s.get("status") == "OK"]
    span_input_sum = sum(
        int(s.get("token_usage", {}).get("prompt_tokens") or 0)
        for s in llm_spans
        if s.get("token_usage", {}).get("prompt_tokens") is not None
    )
    span_output_sum = sum(
        int(s.get("token_usage", {}).get("output_tokens") or 0)
        for s in llm_spans
        if s.get("token_usage", {}).get("output_tokens") is not None
    )
    span_llm_count = sum(
        1 for s in llm_spans
        if s.get("token_usage", {}).get("prompt_tokens") is not None
    )
    gs_signals = gs_data.get("signals", {})
    gs_input = gs_signals.get("input_tokens", 0)
    gs_output = gs_signals.get("output_tokens", 0)
    gs_calls = gs_signals.get("gemini_call_count", 0)
    assert gs_input == span_input_sum, (
        f"Input token mismatch: golden_signals={gs_input}, sum of LLM spans={span_input_sum}"
    )
    assert gs_output == span_output_sum, (
        f"Output token mismatch: golden_signals={gs_output}, sum of LLM spans={span_output_sum}"
    )
    assert gs_calls == span_llm_count, (
        f"Gemini call count mismatch: golden_signals={gs_calls}, LLM spans with tokens={span_llm_count}"
    )
    print(f"  [PASS] input_tokens  : golden={gs_input} == span_sum={span_input_sum}")
    print(f"  [PASS] output_tokens : golden={gs_output} == span_sum={span_output_sum}")
    print(f"  [PASS] gemini_calls  : golden={gs_calls} == span_count={span_llm_count}")

    # ----------------------------------------------------
    # CHECK G: Cost cross-check — notional = centralized pricing
    # ----------------------------------------------------
    print("\n[CHECK G] Cost Cross-Check: notional cost == centralized pricing calculation...")
    gs_notional = gs_signals.get("estimated_notional_cost_usd", 0)
    rates = get_model_pricing(settings.gemini_model)
    expected_cost = round(
        (gs_input * rates["input_cost_per_million"] / 1_000_000.0)
        + (gs_output * rates["output_cost_per_million"] / 1_000_000.0),
        8,
    )
    assert abs(gs_notional - expected_cost) < 1e-7, (
        f"Cost mismatch: golden_signals notional={gs_notional}, centralized calc={expected_cost} "
        f"({gs_input} * {rates['input_cost_per_million']}/1M + {gs_output} * {rates['output_cost_per_million']}/1M)"
    )
    # Ensure CHECK B and CHECK G arrive at the exact same authoritative cost
    assert abs(gs_notional - golden_cost["notional_cost_usd"]) < 1e-7, (
        f"CHECK B and CHECK G cost mismatch: CHECK B={golden_cost['notional_cost_usd']}, CHECK G={gs_notional}"
    )
    print(f"  [PASS] notional_cost: ${gs_notional:.8f} matches centralized pricing at "
          f"${rates['input_cost_per_million']:.2f}/1M in + ${rates['output_cost_per_million']:.2f}/1M out")

    # ----------------------------------------------------
    # CHECK H: evaluation_report.json is machine-generated
    # ----------------------------------------------------
    print("\n[CHECK H] Verifying evaluation_report.json is machine-generated by run_evaluation.py...")
    eval_report_path = root / "reports" / "evaluation_report.json"
    assert eval_report_path.exists(), f"Missing {eval_report_path}"
    with open(eval_report_path, "r", encoding="utf-8") as f:
        eval_report = json.load(f)
    # Machine-generated reports always have a metadata.generated_at timestamp
    eval_meta = eval_report.get("metadata", {})
    generated_at = eval_meta.get("generated_at")
    assert generated_at, "evaluation_report.json is missing metadata.generated_at — indicates manual edit!"
    judge_model = eval_meta.get("judge_model")
    assert judge_model == settings.gemini_model, (
        f"evaluation_report judge_model '{judge_model}' != current settings model '{settings.gemini_model}'"
    )
    qa = eval_report.get("quota_and_token_accounting", {})
    assert qa.get("actual_api_charge_usd") is None, (
        f"evaluation_report actual_api_charge_usd must be null; got: {qa.get('actual_api_charge_usd')}"
    )
    assert qa.get("pricing_basis"), "evaluation_report pricing_basis is missing or empty!"
    print(f"  [PASS] generated_at = {generated_at}")
    print(f"  [PASS] judge_model  = {judge_model}")
    print(f"  [PASS] actual_api_charge_usd = null with note: '{qa.get('actual_api_charge_note', '')}' ")
    print(f"  [PASS] pricing_basis = {qa.get('pricing_basis')[:60]}...")

    # ----------------------------------------------------
    # CHECK I: No secrets or raw PAN leakage
    # ----------------------------------------------------
    print("\n[CHECK I] Verifying PAN Masking & Secrets Hygiene...")
    pan_pattern = re.compile(r"\b(?:4[0-9]{15}|5[1-5][0-9]{14}|3[47][0-9]{13})\b")
    api_key_pattern = re.compile(r"AIzaSy[A-Za-z0-9_-]{33}")

    audit_files = [traces_file, tool_file, action_file, golden_file, dashboard_csv]
    for af in audit_files:
        if af.exists():
            text = af.read_text(encoding="utf-8")
            assert not api_key_pattern.search(text), f"API KEY LEAK DETECTED in {af}!"
            assert not pan_pattern.search(text), f"RAW UNMASKED PAN DETECTED in {af}!"
            print(f"  [PASS] {af.name} is clean of secrets and raw PANs.")

    print("\n" + "=" * 70)
    print("ALL EVIDENCE INTEGRITY AND GOVERNANCE CHECKS PASSED SUCCESSFULLY!")
    print("=" * 70)


if __name__ == "__main__":
    verify_all()
